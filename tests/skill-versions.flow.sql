create or replace function expect_fail(statement text) returns void language plpgsql as $$begin execute statement;raise exception 'TEST SHOULD FAIL';exception when others then if sqlerrm='TEST SHOULD FAIL' then raise;end if;end $$;
do $$declare v public.skill_versions; r public.skill_resources; payload jsonb; rid uuid='20000000-0000-0000-0000-000000000001';
begin
 select jsonb_build_object('title','新版','description',description,'visibility_scope','all_partners','file_name','old.zip','file_path',file_path,'size_bytes',100,'tested',true) into payload from skill_resources where id=rid;
 perform set_config('test.uid','10000000-0000-0000-0000-000000000002',false);
 perform expect_fail(format('select submit_skill_version(%L,1,%L,%L)',rid,payload,'更新'));
 perform set_config('test.uid','10000000-0000-0000-0000-000000000001',false);
 perform expect_fail(format('select submit_skill_version(%L,1,%L,%L)',rid,payload,''));
 perform expect_fail(format('select submit_skill_version(%L,1,%L,%L)',rid,payload||'{"tested":false}'::jsonb,'未试用'));
 perform expect_fail(format('select submit_skill_version(%L,1,%L,%L)',rid,payload||jsonb_build_object('file_path','someone/private.zip'),'非法附件'));
 v:=submit_skill_version(rid,1,payload,'改进步骤并试用');
 select * into r from skill_resources where id=rid;
 assert r.title='旧版' and r.version_number=1 and r.status='published' and r.download_count=7;
 assert (select count(*) from assets)=1;
 perform expect_fail(format('select submit_skill_version(%L,1,%L,%L)',rid,payload,'重复'));
 perform expect_fail(format('select review_skill_version(%L,%L,%L)',v.id,'published','本人越权'));
 perform set_config('test.uid','10000000-0000-0000-0000-000000000004',false);
 perform expect_fail(format('select review_skill_version(%L,%L,%L)',v.id,'published','跨品牌越权'));
 perform set_config('test.uid','10000000-0000-0000-0000-000000000005',false);
 perform expect_fail(format('select review_skill_version(%L,%L,%L)',v.id,'published','领导越权'));
 perform set_config('test.uid','10000000-0000-0000-0000-000000000003',false);
 perform expect_fail(format('select review_skill_version(%L,%L,%L)',v.id,'rejected',''));
 perform review_skill_version(v.id,'rejected','补充试用证据');
 assert (select title from skill_resources where id=rid)='旧版';
 perform set_config('test.uid','10000000-0000-0000-0000-000000000001',false);
 v:=submit_skill_version(rid,1,payload,'补充证据后重提');
 perform set_config('test.uid','10000000-0000-0000-0000-000000000003',false);
 perform review_skill_version(v.id,'published','已核验');
 select * into r from skill_resources where id=rid;
 assert r.title='新版' and r.version_number=2 and r.download_count=7;
 assert (select count(*) from assets)=1 and (select title from assets)='新版';
 assert (select count(*) from operation_audit_logs)=2;
 assert (select count(*) from notifications)=2;
 assert v.previous_payload->>'title'='旧版';
 perform expect_fail(format('select review_skill_version(%L,%L,%L)',v.id,'published','重复审核'));
 perform set_config('test.uid','10000000-0000-0000-0000-000000000001',false);
 perform expect_fail(format('select submit_skill_version(%L,1,%L,%L)',rid,payload,'旧版本并发'));
 v:=submit_skill_version(rid,2,payload||jsonb_build_object('file_path','10000000-0000-0000-0000-000000000001/new.zip','file_name','new.zip'),'替换文件');
 assert (select file_path from skill_resources where id=rid) like '%/old.zip';
 assert v.payload->>'file_path' like '%/new.zip';
 perform set_config('test.uid','10000000-0000-0000-0000-000000000003',false);
 assert public.dfws_can_read_version_file(v.payload->>'file_path');
 update skill_resources set title='管理端修改' where id=rid;
 perform expect_fail(format('select review_skill_version(%L,%L,%L)',v.id,'published','旧版已变动'));
 assert (select status from skill_versions where id=v.id)='pending';
 update skill_resources set title='新版' where id=rid;
 perform review_skill_version(v.id,'published','文件已核验');
 assert (select file_path from skill_resources where id=rid) like '%/new.zip';
 assert (select count(*) from assets)=1;
 perform set_config('test.uid','10000000-0000-0000-0000-000000000002',false);
 assert not public.dfws_can_read_version_file(v.payload->>'file_path');
 perform set_config('test.uid','10000000-0000-0000-0000-000000000001',false);
 update profiles set account_status='disabled' where id=auth.uid();
 perform expect_fail(format('select submit_skill_version(%L,3,%L,%L)',rid,payload,'停用账号'));
 raise notice 'PASS: version submit/reject/resubmit/publish; file retention; audit; no duplicate asset; ownership, brand, leader and disabled-account guards';
end $$;
